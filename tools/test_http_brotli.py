"""Exercise the production JNI stream and HTTP provider with pinned AOSP Brotli.

The host boundary adapts built-in-library registration and the JNI ABI to the
host JVM; it does not replace a decoder, native method, engine or HTTP transport.
The encoder is built separately, only to independently reproduce test vectors.
The product links common/dec, never enc. Run with --write-fixtures only when
intentionally regenerating the checked-in Android/Windows fixture source.
"""
import argparse
import base64
from concurrent.futures import ThreadPoolExecutor
import ctypes
import hashlib
import io
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import tempfile
import textwrap

ROOT = Path(__file__).resolve().parents[1]
REVISION = '39026f8dd0485dddcb0f9f5b12fb5ed788beca43'


def run(command, **kwargs):
    subprocess.run(list(map(str, command)), check=True, timeout=180, **kwargs)


def vectors(library):
    encoder = ctypes.CDLL(str(library))
    size = ctypes.c_size_t
    pointer = ctypes.c_void_p
    encoder.BrotliEncoderCompress.argtypes = [ctypes.c_int, ctypes.c_int, ctypes.c_int,
        size, pointer, ctypes.POINTER(size), pointer]
    encoder.BrotliEncoderCompress.restype = ctypes.c_int
    encoder.BrotliEncoderCreateInstance.argtypes = [pointer, pointer, pointer]
    encoder.BrotliEncoderCreateInstance.restype = pointer
    encoder.BrotliEncoderDestroyInstance.argtypes = [pointer]
    encoder.BrotliEncoderSetParameter.argtypes = [pointer, ctypes.c_int, ctypes.c_uint]
    encoder.BrotliEncoderCompressStream.argtypes = [pointer, ctypes.c_int,
        ctypes.POINTER(size), ctypes.POINTER(pointer), ctypes.POINTER(size),
        ctypes.POINTER(pointer), ctypes.POINTER(size)]
    encoder.BrotliEncoderCompressStream.restype = ctypes.c_int
    encoder.BrotliEncoderHasMoreOutput.argtypes = [pointer]
    encoder.BrotliEncoderIsFinished.argtypes = [pointer]

    def compress(data):
        length = size(len(data) + 1024)
        output = ctypes.create_string_buffer(length.value)
        if not encoder.BrotliEncoderCompress(5, 22, 1, len(data), data, ctypes.byref(length), output):
            raise RuntimeError('Fixture compression failed')
        return output.raw[:length.value]

    state = encoder.BrotliEncoderCreateInstance(None, None, None)
    if not state:
        raise MemoryError('Cannot allocate fixture encoder')
    try:
        if not encoder.BrotliEncoderSetParameter(state, 1, 5):
            raise RuntimeError('Cannot set fixture quality')
        def stream(data, operation):
            source = ctypes.create_string_buffer(data)
            next_input = pointer(ctypes.addressof(source))
            available_input = size(len(data))
            pieces = []
            while True:
                output = ctypes.create_string_buffer(4096)
                next_output = pointer(ctypes.addressof(output))
                available_output = size(len(output))
                if not encoder.BrotliEncoderCompressStream(state, operation,
                        ctypes.byref(available_input), ctypes.byref(next_input),
                        ctypes.byref(available_output), ctypes.byref(next_output), None):
                    raise RuntimeError('Fixture stream compression failed')
                pieces.append(output.raw[:len(output)-available_output.value])
                if not available_input.value and not encoder.BrotliEncoderHasMoreOutput(state):
                    break
            return b''.join(pieces)
        prefix = stream(b'ping', 1)  # FLUSH, without finishing the stream.
        suffix = stream(b'pong', 2)  # FINISH the same stream.
        if not encoder.BrotliEncoderIsFinished(state):
            raise RuntimeError('Fixture stream was not finished')
    finally:
        encoder.BrotliEncoderDestroyInstance(state)

    payload = ''.join('{"id":%d,"title":"Android application record %d","enabled":true,'
        '"description":"A real incremental HTTP response keeps callbacks and cancellation responsive."}\n'
        % (i, i % 73) for i in range(8192)).encode()
    data = {'EMPTY': compress(b''), 'PING': compress(b'ping'),
            'FLUSH_PING': prefix, 'FINISH_PONG': suffix, 'RECORDS': compress(payload)}
    lines = ['// Generated by tools/test_http_brotli.py --write-fixtures.',
        '// Pinned Android 16 r4 Brotli encoder '+REVISION+'; quality 5, RFC 7932.',
        '// Copyright (C) 2026 The Gesher Authors; SPDX-License-Identifier: Apache-2.0',
        'package android.net.http;', '', 'public final class HttpBrotliFixtures {',
        '    private HttpBrotliFixtures() {}',
        '    public static final String PAYLOAD_SHA256 = "'+hashlib.sha256(payload).hexdigest()+'";']
    for name, value in data.items():
        encoded = textwrap.wrap(base64.b64encode(value).decode(), 96)
        lines += ['    public static final byte[] '+name+' = java.util.Base64.getDecoder().decode(']
        lines += ['        "'+part+'"'+(' +' if i+1<len(encoded) else ');')
                  for i, part in enumerate(encoded)]
    lines += ['}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--brotli-source', type=Path, required=True)
    parser.add_argument('--okhttp-source', type=Path)
    parser.add_argument('--java-home', type=Path, required=True)
    parser.add_argument('--write-fixtures', action='store_true')
    parser.add_argument('--output-dir', type=Path)
    args = parser.parse_args()
    revision = subprocess.check_output(['git','rev-parse','HEAD'], cwd=args.brotli_source,
                                       text=True).strip()
    if revision != REVISION:
        raise RuntimeError('Brotli tests require unchanged android-16.0.0_r4')
    temporary = tempfile.TemporaryDirectory(prefix='gesher-http-brotli-')
    output = args.output_dir.resolve() if args.output_dir else Path(temporary.name)
    output.mkdir(parents=True, exist_ok=True)
    source = output/'provider'; source.mkdir(exist_ok=True)
    archive = subprocess.check_output(['git','archive',REVISION,'c/common','c/dec','c/enc','c/include'],
                                      cwd=args.brotli_source)
    with tarfile.open(fileobj=io.BytesIO(archive)) as tree:
        tree.extractall(source, filter='data')
    print('BROTLI_PROVIDER '+REVISION, flush=True)
    include = source/'c/include'
    objects = output/'objects'; objects.mkdir(exist_ok=True)
    common = sorted((source/'c/common').glob('*.c'))
    decode = sorted((source/'c/dec').glob('*.c'))
    encode = sorted((source/'c/enc').glob('*.c'))
    def compile_one(path):
        obj = objects/(path.parent.name+'-'+path.stem+'.o')
        run(['gcc','-std=c11','-O2','-g','-fPIC','-fsanitize=undefined',
             '-fno-sanitize-recover=all','-I',include,'-c',path,'-o',obj])
        return obj
    with ThreadPoolExecutor(max_workers=4) as workers:
        compiled = dict(zip(common+decode+encode, workers.map(compile_one, common+decode+encode)))
    encoder = output/'libbrotli_fixture_encoder.so'
    run(['gcc','-shared','-fsanitize=undefined',*[compiled[p] for p in common+encode],'-lm','-o',encoder])
    expected = vectors(encoder)
    fixture = ROOT/'tests/net/HttpBrotliFixtures.java'
    if args.write_fixtures:
        fixture.write_text(expected)
    elif fixture.read_text() != expected:
        raise RuntimeError('Brotli test vectors differ from the pinned independent encoder')
    shim_include = output/'include/nativehelper'; shim_include.mkdir(parents=True, exist_ok=True)
    (shim_include/'jni_macros.h').write_text('#pragma once\n'
        '#define NATIVEHELPER_SYSV_JNI_ENTRY(f) reinterpret_cast<void*>(&f)\n')
    builtin_include = output/'include/gesher'; builtin_include.mkdir(exist_ok=True)
    shutil.copyfile(ROOT/'compat/posix/include/gesher/builtin_library.h',
                    builtin_include/'builtin_library.h')
    shim = output/'builtin_host.cc'
    shim.write_text('''#include <jni.h>
#include <gesher/builtin_library.h>
#include <cstring>
#include <cstdlib>
static jint (*load)(JavaVM*,void*);
extern "C" void gesher_register_builtin_library(const char* name,
        const gesher_builtin_symbol* symbols, size_t count) {
    if (std::strcmp(name,"libgesher_brotli.so") || count!=1 ||
            std::strcmp(symbols[0].name,"JNI_OnLoad")) std::abort();
    load=reinterpret_cast<jint (*)(JavaVM*,void*)>(symbols[0].address);
}
extern "C" JNIEXPORT jint JNICALL JNI_OnLoad(JavaVM* vm,void* reserved) {
    return load ? load(vm,reserved) : JNI_ERR;
}
''')
    native = ROOT/'compat/net/brotli_jni.cc'
    run(['g++','-std=c++17','-O2','-g','-fPIC','-shared','-fsanitize=undefined',
         '-fno-sanitize-recover=all','-I',output/'include','-I',args.java_home/'include',
         '-I',args.java_home/'include/linux','-I',include,
         native,shim,*[compiled[p] for p in common+decode],'-o',output/'libgesher_brotli.so'])
    print('BROTLI_JNI_SHA256 '+hashlib.sha256(native.read_bytes()).hexdigest(), flush=True)
    if args.okhttp_source:
        from test_http_engine import prepare_provider
        provider = prepare_provider(args.okhttp_source, output/'okhttp-provider', None)
        run([sys.executable,ROOT/'tools/test_http_engine_policy.py','--java-home',args.java_home,
             '--okhttp-source',provider,'--brotli-native',output,'--brotli-only'])
    elif not args.write_fixtures:
        raise RuntimeError('HTTP/Brotli validation requires --okhttp-source')
    temporary.cleanup()


if __name__ == '__main__':
    main()
