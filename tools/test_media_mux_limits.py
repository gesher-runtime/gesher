#!/usr/bin/env python3
"""Verify complete MP4/3GPP/Ogg/ADTS/WebM budgets using real writer TUs and libwebm.

Format is a declared host map seam. All input packets are generated by FFmpeg,
never injected into a production capture path. FFprobe/FFmpeg independently
parse and decode the finalized limited files. No Windows/ART run is implied.
"""
from __future__ import annotations
import argparse
import json
import os
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]

def run(argv, **kw):
    return subprocess.run(list(map(str, argv)), check=True, timeout=120, **kw)

def pack_units(path, packets):
    path.write_bytes(b''.join(struct.pack('<I', len(p)) + p for p in packets))

def check(work, libwebm):
    run(['ffmpeg', '-y', '-v', 'error', '-f', 'lavfi', '-i', 'anullsrc=r=48000:cl=mono',
         '-t', '1', '-c:a', 'aac', '-b:a', '96000', '-f', 'adts', work / 'silence.aac'])
    run(['ffmpeg', '-y', '-v', 'error', '-f', 'lavfi', '-i', 'sine=frequency=750:sample_rate=48000',
         '-t', '1', '-c:a', 'libopus', '-b:a', '96000', '-f', 'ogg', work / 'tone.ogg'])
    run(['ffmpeg', '-y', '-v', 'error', '-f', 'lavfi', '-i', 'color=red:size=32x32',
         '-frames:v', '1', '-c:v', 'libx264', '-f', 'h264', work / 'frame.h264'])
    aac = (work / 'silence.aac').read_bytes(); units = []; at = 0
    while at < len(aac):
        assert aac[at] == 0xff and aac[at+1] & 0xf1 == 0xf1
        length = ((aac[at+3] & 3) << 11) | (aac[at+4] << 3) | (aac[at+5] >> 5)
        units.append(aac[at+7:at+length]); at += length
    pack_units(work / 'aac.units', units)
    ogg = (work / 'tone.ogg').read_bytes(); packets = []; packet = bytearray(); at = 0
    while at < len(ogg):
        assert ogg[at:at+4] == b'OggS'
        count = ogg[at+26]; lacing = ogg[at+27:at+27+count]; at += 27+count
        for size in lacing:
            packet += ogg[at:at+size]; at += size
            if size < 255: packets.append(bytes(packet)); packet.clear()
    assert not packet and packets[0].startswith(b'OpusHead') and packets[1].startswith(b'OpusTags')
    (work / 'opus.head').write_bytes(packets[0]); pack_units(work / 'opus.units', packets[2:])
    media = ROOT / 'compat/media'
    command = [os.environ.get('CXX', 'c++'), '-std=c++20', '-O1', '-g', '-fno-exceptions',
        '-Wall', '-Wextra', '-Werror', '-Wno-unused-parameter', '-DGESHER_MEDIA_STANDALONE',
        '-fsanitize=undefined', '-fno-sanitize-recover=undefined', '-I', ROOT,
        '-I', ROOT / 'tests/media/recorder-host/include', '-I', libwebm,
        ROOT / 'tests/media/recorder-host/mux_limits.cc', media / 'mux/mp4_muxer.cc',
        media / 'mux/ogg_muxer.cc', media / 'mux/webm_muxer.cc', media / 'encode/codec_config.cc',
        libwebm / 'mkvmuxer/mkvmuxer.cc', libwebm / 'mkvmuxer/mkvmuxerutil.cc',
        libwebm / 'mkvmuxer/mkvwriter.cc', '-o', work / 'mux-limits']
    run(command)
    run([work / 'mux-limits', work])
    results = []
    for path in sorted(work.glob('[0-9]*-*')):
        if not path.is_file(): continue
        limit = int(path.name.split('-')[0]); assert 0 < path.stat().st_size < limit
        probe = run(['ffprobe', '-v', 'error', '-count_packets', '-show_streams', '-of', 'json', path], capture_output=True, text=True)
        info = json.loads(probe.stdout); assert info['streams']
        assert all(int(stream['nb_read_packets']) > 0 for stream in info['streams'])
        run(['ffmpeg', '-v', 'error', '-xerror', '-i', path, '-f', 'null', '-'], capture_output=True, text=True)
        results.append({'file': path.name, 'limit': limit, 'bytes': path.stat().st_size,
                        'codecs': [s['codec_name'] for s in info['streams']]})
    (work / 'results.json').write_text(json.dumps(results, indent=2) + '\n')
    print(f'{len(results)} limited containers independently demuxed and decoded', flush=True)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--libwebm', required=True, type=Path, help='external/libwebm from the configured AOSP checkout')
    parser.add_argument('--out', type=Path, help='retain generated test evidence in this directory')
    args = parser.parse_args()
    if args.out:
        args.out.mkdir(parents=True, exist_ok=True); check(args.out.resolve(), args.libwebm.resolve())
    else:
        with tempfile.TemporaryDirectory(prefix='gesher-mux-limits-') as temp:
            check(Path(temp), args.libwebm.resolve())
if __name__ == '__main__': main()
