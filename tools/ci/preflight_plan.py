def direct_script_groups(paths):
    """Return all owning groups, or None when a path needs broader analysis."""
    if not paths or set(paths) - SCRIPT_GROUPS.keys():
        return None
    return set().union(*(SCRIPT_GROUPS[path] for path in paths))


def validate_steps(steps):
    """Reject a dropped, repeated or unclassified check before selection."""
    names = [step["name"] for step in steps if "run" in step]
    expected = STEP_GROUPS.keys() | SETUP_STEPS
    if set(names) != expected or any(count != 1 for count in Counter(names).values()):
        raise ValueError("preflight checks must each be classified exactly once")
    if set(STEP_GROUPS.values()) != set(GROUPS):
        raise ValueError("preflight group inventory differs from its step classification")
