#!/usr/bin/env python3
"""Generate the Java classes Soong's java_aconfig_library would produce.

    aconfig_java.py <values> <out dir> <flags.aconfig>...

Declarations of one package may be split over several files, as an
aconfig_declarations module's srcs are; they are merged. Writes, for each
package, under <out dir>/<package path>/, the read-only API: Flags.java, with
a FLAG_<NAME> constant holding "<package>.<name>" and a static accessor
<camelCaseName>() per flag; the FeatureFlags interface; and FeatureFlagsImpl,
which answers from Flags. Values work as in aconfig_header.py.
"""
import os
import sys

from aconfig_header import flag_value, parse_aconfig, parse_values

HEADER = '// Generated by gesher tools/gen/aconfig_java.py. Do not edit.'


def camel(name):
    head, *rest = name.split('_')
    return head + ''.join(w[:1].upper() + w[1:] for w in rest)


def write(out_dir, package, cls, lines):
    path = os.path.join(out_dir, *package.split('.'), f'{cls}.java')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', newline='\n') as f:
        f.write('\n'.join([HEADER, f'package {package};', '', '/** @hide */',
                           *lines, '']))


def main():
    values = parse_values(sys.argv[1])
    out_dir = sys.argv[2]
    packages = {}
    for path in sys.argv[3:]:
        with open(path, encoding='utf-8') as f:
            package, names = parse_aconfig(f.read())
        if package:
            packages.setdefault(package, []).extend(names)
    for package, names in sorted(packages.items()):
        generate(out_dir, package, names, values)


def generate(out_dir, package, names, values):
    flags = ['public final class Flags {', '    private Flags() {}', '']
    for name in names:
        flags.append(f'    public static final String FLAG_{name.upper()} = "{package}.{name}";')
    flags.append('')
    for name in names:
        value = 'true' if flag_value(values, package, name) else 'false'
        flags.append(f'    public static boolean {camel(name)}() {{ return {value}; }}')
    write(out_dir, package, 'Flags', flags + ['}'])

    write(out_dir, package, 'FeatureFlags', [
        'public interface FeatureFlags {',
        *(f'    boolean {camel(name)}();' for name in names),
        '}'])

    write(out_dir, package, 'FeatureFlagsImpl', [
        'public final class FeatureFlagsImpl implements FeatureFlags {',
        *(f'    @Override public boolean {camel(name)}() {{ return Flags.{camel(name)}(); }}'
          for name in names),
        '}'])


if __name__ == '__main__':
    main()
