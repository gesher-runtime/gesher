#!/usr/bin/env python3
"""Generate the Java Flags class Soong's java_aconfig_library would produce.

    aconfig_java.py <flags.aconfig> <values> <out dir>

Writes <out dir>/<package path>/Flags.java with the read-only API: a
FLAG_<NAME> constant holding "<package>.<name>" and a static accessor
<camelCaseName>() per flag. Values work as in aconfig_header.py.
"""
import os
import sys

from aconfig_header import parse_aconfig, parse_values


def camel(name):
    head, *rest = name.split('_')
    return head + ''.join(w[:1].upper() + w[1:] for w in rest)


def main():
    with open(sys.argv[1]) as f:
        package, names = parse_aconfig(f.read())
    values = parse_values(sys.argv[2])
    out = [
        '// Generated by gesher tools/gen/aconfig_java.py. Do not edit.',
        f'package {package};',
        '',
        '/** @hide */',
        'public final class Flags {',
        '    private Flags() {}',
        '',
    ]
    for name in names:
        out.append(f'    public static final String FLAG_{name.upper()} = "{package}.{name}";')
    out.append('')
    for name in names:
        value = 'true' if values.get(name, False) else 'false'
        out.append(f'    public static boolean {camel(name)}() {{ return {value}; }}')
    out += ['}', '']
    path = os.path.join(sys.argv[3], *package.split('.'), 'Flags.java')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', newline='\n') as f:
        f.write('\n'.join(out))


if __name__ == '__main__':
    main()
