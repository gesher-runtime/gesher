#!/usr/bin/env python3
"""Generate checked-in UI resources. Run --check in CI; edit messages.json only."""
import argparse
import json
import re
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "tools/i18n/messages.json"


def outputs():
    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    languages = list(data["languages"])
    messages = data["messages"]
    for key, translations in messages.items():
        if set(translations) != set(languages):
            raise ValueError(f"{key}: missing/unknown language")
        expected = sorted(re.findall(r"\{\d+\}", translations["en"]))
        for lang, value in translations.items():
            if not value or sorted(re.findall(r"\{\d+\}", value)) != expected:
                raise ValueError(f"{key}/{lang}: empty text or incompatible placeholders")
    quote = lambda s: json.dumps(s, ensure_ascii=True)
    java = ['// Generated by tools/i18n/generate.py; do not edit.',
            'package com.gesher.app.locale;', 'import java.util.Locale;',
            'public final class UiMessages {', '    private UiMessages() {}',
            '    public static String language(String tags) {',
            '        if (tags != null) for (String tag : tags.split(",")) {',
            '            String lang = tag.trim().toLowerCase(Locale.ROOT).split("[-_]", 2)[0];',
            '            if (lang.equals("iw")) lang = "he";']
    for lang in languages:
        java.append(f'            if (lang.equals("{lang}")) return lang;')
    java += ['        }', '        return "en";', '    }',
             '    public static String[] supportedLanguages() {',
             '        return new String[] {' + ', '.join(quote(lang) for lang in languages) + '};',
             '    }',
             '    public static boolean isRtl(String tags) {',
             '        switch (language(tags)) {']
    for lang in languages:
        if data["languages"][lang]["rtl"]:
            java.append(f'            case "{lang}": return true;')
    java += ['            default: return false;', '        }', '    }',
             '    public static String text(String key, String tags, Object... args) {',
             '        String lang = language(tags);', '        String value;', '        switch (key) {']
    for key, translations in messages.items():
        expression = quote(translations["en"])
        for lang in reversed(languages[1:]):
            expression = f'lang.equals("{lang}") ? {quote(translations[lang])} : {expression}'
        java.append(f'            case "{key}": value = {expression}; break;')
    java += ['            default: throw new IllegalArgumentException("Unknown UI text: " + key);',
             '        }',
             '        // Replace in one pass: user data containing {1} is never a template.',
             '        StringBuilder out = new StringBuilder();',
             '        java.util.regex.Matcher m = java.util.regex.Pattern.compile("\\\\{(\\\\d+)\\\\}").matcher(value);',
             '        int at = 0;', '        while (m.find()) {',
             '            int index = Integer.parseInt(m.group(1));',
             '            if (index >= args.length) throw new IllegalArgumentException("Missing UI argument");',
             '            out.append(value, at, m.start()).append(String.valueOf(args[index]));',
             '            at = m.end();', '        }',
             '        return out.append(value, at, value.length()).toString();', '    }', '}']
    header = ['// Generated by tools/i18n/generate.py; do not edit.', '#pragma once',
              '#include <wchar.h>', 'enum GesherUiLanguage {']
    header += [f'  GESHER_UI_{lang.upper()},' for lang in languages]
    header += ['};', 'static inline enum GesherUiLanguage GesherUiMatch(const wchar_t* tags) {',
               '  const wchar_t* p = tags;', '  while (p != NULL && *p) {',
               "    while (*p == L' ' || *p == L',' || *p == L'\\t') ++p;",
               '    const wchar_t* start = p;', "    while (*p && *p != L',') ++p;",
               '    size_t n = (size_t)(p - start);',
               "    while (n && (start[n-1] == L' ' || start[n-1] == L'\\t')) --n;"]
    for lang in languages:
        aliases = [lang] + (["iw"] if lang == "he" else [])
        for alias in aliases:
            header += [f'    if (n >= {len(alias)} && _wcsnicmp(start, L"{alias}", {len(alias)}) == 0',
                       f"        && (n == {len(alias)} || start[{len(alias)}] == L'-' || start[{len(alias)}] == L'_')) return GESHER_UI_{lang.upper()};"]
    header += ['  }', '  return GESHER_UI_EN;', '}',
               'static inline int GesherUiRtl(enum GesherUiLanguage lang) {',
               '  return ' + ' || '.join(f'lang == GESHER_UI_{l.upper()}' for l in languages if data['languages'][l]['rtl']) + ';', '}',
               'static inline const wchar_t* GesherUiText(enum GesherUiLanguage lang, const char* key) {']
    header.insert(3, '#include <string.h>')
    for key, translations in messages.items():
        expression = 'L' + quote(translations['en'])
        for lang in reversed(languages[1:]):
            expression = f'lang == GESHER_UI_{lang.upper()} ? L{quote(translations[lang])} : {expression}'
        header.append(f'  if (strcmp(key, "{key}") == 0) return {expression};')
    header += ['  return L"";', '}']
    result = {ROOT / 'app/java/com/gesher/app/locale/UiMessages.java': '\n'.join(java) + '\n',
              ROOT / 'compat/locale/ui_messages.h': '\n'.join(header) + '\n'}
    inno = ['; Generated by tools/i18n/generate.py; do not edit.', '[CustomMessages]']
    for lang in languages:
        for key, translations in messages.items():
            if key.startswith('setup_'):
                inno.append(f'{lang}.{key}=' + translations[lang].replace('\n', '%n'))
        xml = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/i18n/generate.py; do not edit. -->', '<resources>']
        for key in ('camera_name', 'camera_take', 'camera_cancel'):
            xml.append(f'    <string name="{dict(camera_name="app_name", camera_take="take", camera_cancel="cancel")[key]}">{escape(messages[key][lang]).replace(chr(39), chr(92)+chr(39))}</string>')
        xml += ['</resources>']
        folder = 'values' if lang == 'en' else f'values-{lang}'
        result[ROOT / f'app/gesher-camera/res/{folder}/strings.xml'] = '\n'.join(xml) + '\n'
    # Remove every language's Start menu folder, even if Windows' language changed.
    inno += ['', '[UninstallDelete]']
    for folder in dict.fromkeys(messages['apps_folder'].values()):
        inno.append('Type: filesandordirs; Name: "{userprograms}\\' + folder + '"')
    result[ROOT / 'tools/package/ui-messages.iss'] = '\n'.join(inno) + '\n'
    result[ROOT / 'tools/package/ui-messages.json'] = json.dumps(data, ensure_ascii=False, indent=2) + '\n'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    if stale:
        parser.exit(1, 'Run python tools/i18n/generate.py: ' + ', '.join(stale) + '\n')


if __name__ == '__main__':
    main()
