package com.gesher.app;

import android.content.Intent;
import android.content.IntentFilter;
import android.content.pm.ActivityInfo;
import android.content.pm.ApplicationInfo;
import android.content.pm.ComponentInfo;
import android.content.pm.PackageInfo;
import android.content.pm.PackageManager;
import android.content.res.ApkAssets;
import android.content.res.XmlResourceParser;
import android.os.Process;

import com.android.internal.pm.parsing.PackageInfoCommonUtils;
import com.android.internal.pm.parsing.PackageParser2;
import com.android.internal.pm.parsing.pkg.ParsedPackage;
import com.android.internal.pm.pkg.component.ParsedActivity;
import com.android.internal.pm.pkg.component.ParsedIntentInfo;

import org.xmlpull.v1.XmlPullParser;

import java.io.File;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Set;

/**
 * An APK's manifest, as the {@link ApplicationInfo}, {@link ActivityInfo}s and
 * {@link PackageInfo} that PackageManagerService would hand an app.
 *
 * <p>The APK is parsed the way PackageManagerService parses it at install: framework.jar's
 * {@link PackageParser2} (ParsingPackageUtils: the whole manifest, with services,
 * receivers, providers, permissions, meta-data and intent filters), and PackageInfos are
 * generated by {@link PackageInfoCommonUtils}, the framework's PackageInfoUtils for
 * packages that are not installed. Certificates are not collected. Should PackageParser2
 * fail, a minimal reader of the binary manifest ({@link ApkAssets#openXml}: package,
 * uses-sdk, application and activities) is the fallback, and says so on stderr.
 */
final class AppManifest {
    static final String ANDROID_NS = "http://schemas.android.com/apk/res/android";

    /** What the PackageInfo holds: every component, with meta-data. */
    static final long PACKAGE_INFO_FLAGS = PackageManager.GET_ACTIVITIES
            | PackageManager.GET_RECEIVERS | PackageManager.GET_SERVICES
            | PackageManager.GET_PROVIDERS | PackageManager.GET_META_DATA
            | PackageManager.GET_CONFIGURATIONS | PackageManager.GET_PERMISSIONS
            | PackageManager.GET_SHARED_LIBRARY_FILES
            | PackageManager.MATCH_DIRECT_BOOT_AWARE | PackageManager.MATCH_DIRECT_BOOT_UNAWARE;

    final String apkPath;
    ApplicationInfo applicationInfo = new ApplicationInfo();
    final List<ActivityInfo> activities = new ArrayList<>();
    final List<String> launcherActivities = new ArrayList<>();
    String versionName;
    long versionCode;
    /** The parsed package; null when the minimal reader read the manifest. */
    ParsedPackage parsedPackage;

    private AppManifest(String apkPath) {
        this.apkPath = apkPath;
    }

    static AppManifest read(String apkPath) throws Exception {
        try {
            return parse(apkPath);
        } catch (Throwable t) {
            System.err.println("gesher-app: PackageParser2 failed on " + apkPath + " (" + t
                    + "); reading the manifest with the minimal reader");
            t.printStackTrace();
            return readMinimal(apkPath);
        }
    }

    // --- PackageParser2 ---------------------------------------------------------------

    /** PackageParser2's callback outside system_server: no compat change is enforced. */
    private static final class ParserCallback extends PackageParser2.Callback {
        @Override
        public boolean isChangeEnabled(long changeId, ApplicationInfo appInfo) {
            return false;
        }

        @Override
        public boolean hasFeature(String feature) {
            return false;
        }

        @Override
        public Set<String> getHiddenApiWhitelistedApps() {
            return Collections.emptySet();
        }

        @Override
        public Set<String> getInstallConstraintsAllowlist() {
            return Collections.emptySet();
        }
    }

    /** Parses the APK as PackageManagerService does, with PackageParser2. */
    static AppManifest parse(String apkPath) throws Exception {
        AppManifest m = new AppManifest(apkPath);
        ParsedPackage pkg;
        try (PackageParser2 parser = new PackageParser2(null /* separateProcesses */,
                null /* displayMetrics: the defaults */, null /* cacher */,
                new ParserCallback())) {
            pkg = parser.parsePackage(new File(apkPath), 0 /* flags */, false /* useCaches */);
        }
        m.parsedPackage = pkg;
        PackageInfo pi = PackageInfoCommonUtils.generate(pkg, PACKAGE_INFO_FLAGS,
                0 /* userId */);
        m.applicationInfo = pi.applicationInfo;
        m.versionName = pi.versionName;
        m.versionCode = pi.getLongVersionCode();
        if (pi.activities != null) {
            Collections.addAll(m.activities, pi.activities);
        }
        for (ParsedActivity a : pkg.getActivities()) {
            for (ParsedIntentInfo info : a.getIntents()) {
                IntentFilter filter = info.getIntentFilter();
                if (filter.hasAction(Intent.ACTION_MAIN)
                        && filter.hasCategory(Intent.CATEGORY_LAUNCHER)) {
                    m.launcherActivities.add(a.getName());
                    break;
                }
            }
        }
        m.finish();
        Main.log(m.applicationInfo.packageName + " parsed by PackageParser2: "
                + m.activities.size() + " activities, " + count(pi.services) + " services, "
                + count(pi.receivers) + " receivers, " + count(pi.providers) + " providers");
        return m;
    }

    private static int count(Object[] a) {
        return a == null ? 0 : a.length;
    }

    // --- the minimal reader -----------------------------------------------------------

    static AppManifest readMinimal(String apkPath) throws Exception {
        AppManifest m = new AppManifest(apkPath);
        ApkAssets assets = ApkAssets.loadFromPath(apkPath);
        try (XmlResourceParser parser = assets.openXml("AndroidManifest.xml")) {
            m.parseMinimal(parser);
        } finally {
            assets.close();
        }
        m.finish();
        return m;
    }

    private void parseMinimal(XmlResourceParser p) throws Exception {
        ApplicationInfo ai = applicationInfo;
        ai.targetSdkVersion = 0;
        ai.minSdkVersion = 1;
        ai.flags = ApplicationInfo.FLAG_HAS_CODE
                | ApplicationInfo.FLAG_SUPPORTS_SMALL_SCREENS
                | ApplicationInfo.FLAG_SUPPORTS_NORMAL_SCREENS
                | ApplicationInfo.FLAG_SUPPORTS_LARGE_SCREENS
                | ApplicationInfo.FLAG_SUPPORTS_XLARGE_SCREENS
                | ApplicationInfo.FLAG_RESIZEABLE_FOR_SCREENS
                | ApplicationInfo.FLAG_SUPPORTS_SCREEN_DENSITIES
                | ApplicationInfo.FLAG_ALLOW_BACKUP;
        ActivityInfo activity = null;  // the <activity> being read
        boolean inFilter = false;
        boolean main = false;
        boolean launcher = false;
        int type;
        while ((type = p.next()) != XmlPullParser.END_DOCUMENT) {
            if (type == XmlPullParser.END_TAG) {
                switch (p.getName()) {
                    case "activity":
                        activity = null;
                        break;
                    case "intent-filter":
                        if (activity != null && main && launcher) {
                            launcherActivities.add(activity.name);
                        }
                        inFilter = false;
                        break;
                }
                continue;
            }
            if (type != XmlPullParser.START_TAG) {
                continue;
            }
            switch (p.getName()) {
                case "manifest":
                    ai.packageName = p.getAttributeValue(null, "package");
                    versionName = p.getAttributeValue(ANDROID_NS, "versionName");
                    versionCode = p.getAttributeIntValue(ANDROID_NS, "versionCode", 0)
                            & 0xffffffffL;
                    break;
                case "uses-sdk":
                    ai.minSdkVersion = p.getAttributeIntValue(ANDROID_NS, "minSdkVersion", 1);
                    ai.targetSdkVersion = p.getAttributeIntValue(ANDROID_NS,
                            "targetSdkVersion", ai.minSdkVersion);
                    break;
                case "application":
                    String appClass = p.getAttributeValue(ANDROID_NS, "name");
                    if (appClass != null) {
                        ai.className = qualify(appClass);
                        ai.name = ai.className;
                    }
                    ai.theme = p.getAttributeResourceValue(ANDROID_NS, "theme", 0);
                    ai.labelRes = p.getAttributeResourceValue(ANDROID_NS, "label", 0);
                    if (ai.labelRes == 0) {
                        ai.nonLocalizedLabel = p.getAttributeValue(ANDROID_NS, "label");
                    }
                    ai.icon = p.getAttributeResourceValue(ANDROID_NS, "icon", 0);
                    if (p.getAttributeBooleanValue(ANDROID_NS, "debuggable", false)) {
                        ai.flags |= ApplicationInfo.FLAG_DEBUGGABLE;
                    }
                    if (!p.getAttributeBooleanValue(ANDROID_NS, "hasCode", true)) {
                        ai.flags &= ~ApplicationInfo.FLAG_HAS_CODE;
                    }
                    String factory = p.getAttributeValue(ANDROID_NS, "appComponentFactory");
                    if (factory != null) {
                        ai.appComponentFactory = qualify(factory);
                    }
                    break;
                case "activity":
                    activity = new ActivityInfo();
                    activity.name = qualify(p.getAttributeValue(ANDROID_NS, "name"));
                    activity.theme = p.getAttributeResourceValue(ANDROID_NS, "theme", 0);
                    activity.labelRes = p.getAttributeResourceValue(ANDROID_NS, "label", 0);
                    if (activity.labelRes == 0) {
                        activity.nonLocalizedLabel = p.getAttributeValue(ANDROID_NS, "label");
                    }
                    activity.exported = p.getAttributeBooleanValue(ANDROID_NS, "exported",
                            false);
                    activity.launchMode = ActivityInfo.LAUNCH_MULTIPLE;
                    activity.screenOrientation = ActivityInfo.SCREEN_ORIENTATION_UNSPECIFIED;
                    activity.resizeMode = ActivityInfo.RESIZE_MODE_RESIZEABLE;
                    activities.add(activity);
                    break;
                case "intent-filter":
                    inFilter = true;
                    main = false;
                    launcher = false;
                    break;
                case "action":
                    if (inFilter && "android.intent.action.MAIN".equals(
                            p.getAttributeValue(ANDROID_NS, "name"))) {
                        main = true;
                    }
                    break;
                case "category":
                    if (inFilter && "android.intent.category.LAUNCHER".equals(
                            p.getAttributeValue(ANDROID_NS, "name"))) {
                        launcher = true;
                    }
                    break;
            }
        }
    }

    private String qualify(String name) {
        if (name == null) {
            return null;
        }
        if (name.startsWith(".")) {
            return applicationInfo.packageName + name;
        }
        if (name.indexOf('.') < 0) {
            return applicationInfo.packageName + "." + name;
        }
        return name;
    }

    // --- the installed package ----------------------------------------------------------

    /** Fills in what an installed package's ApplicationInfo has beyond the manifest. */
    private void finish() {
        ApplicationInfo ai = applicationInfo;
        if (ai.packageName == null) {
            throw new IllegalStateException(apkPath + ": the manifest has no package name");
        }
        if (ai.targetSdkVersion == 0) {
            ai.targetSdkVersion = ai.minSdkVersion;
        }
        if (ai.processName == null) {
            ai.processName = ai.packageName;
        }
        installed(ai);
        for (ActivityInfo a : activities) {
            component(a, ai);
        }
    }

    /** What installing gives a package beyond its manifest: paths, uid, enabled. */
    private void installed(ApplicationInfo ai) {
        ai.sourceDir = apkPath;
        ai.publicSourceDir = apkPath;
        ai.uid = Process.myUid();
        ai.enabled = true;
        ai.flags |= ApplicationInfo.FLAG_INSTALLED;
        if (applicationInfo.dataDir != null && ai != applicationInfo) {
            ai.dataDir = applicationInfo.dataDir;
            ai.credentialProtectedDataDir = applicationInfo.credentialProtectedDataDir;
            ai.deviceProtectedDataDir = applicationInfo.deviceProtectedDataDir;
            ai.nativeLibraryDir = applicationInfo.nativeLibraryDir;
        }
    }

    private static void component(ComponentInfo c, ApplicationInfo ai) {
        c.applicationInfo = ai;
        c.packageName = ai.packageName;
        if (c.processName == null) {
            c.processName = ai.processName;
        }
        c.enabled = true;
    }

    void setDataDir(String dataDir) {
        ApplicationInfo ai = applicationInfo;
        ai.dataDir = dataDir;
        ai.credentialProtectedDataDir = dataDir;
        ai.deviceProtectedDataDir = dataDir;
        ai.nativeLibraryDir = dataDir + "/lib";
    }

    /** The Activity to launch: {@code requested}, or the first MAIN/LAUNCHER one. */
    ActivityInfo launcherActivity(String requested) {
        String name = requested != null ? qualify(requested)
                : !launcherActivities.isEmpty() ? launcherActivities.get(0)
                : null;
        if (name == null) {
            throw new IllegalStateException(apkPath + " has no MAIN/LAUNCHER activity;"
                    + " name one with --activity");
        }
        for (ActivityInfo a : activities) {
            if (a.name.equals(name)) {
                return a;
            }
        }
        throw new IllegalStateException(apkPath + " declares no activity " + name);
    }

    ActivityInfo findActivity(String className) {
        for (ActivityInfo a : activities) {
            if (a.name.equals(className)) {
                return a;
            }
        }
        return null;
    }

    /** The package's PackageInfo, a new one per call. */
    PackageInfo packageInfo() {
        PackageInfo pi;
        if (parsedPackage != null) {
            pi = PackageInfoCommonUtils.generate(parsedPackage, PACKAGE_INFO_FLAGS,
                    0 /* userId */);
            installed(pi.applicationInfo);
            for (ComponentInfo[] components : new ComponentInfo[][] {pi.activities,
                    pi.receivers, pi.services, pi.providers}) {
                if (components == null) continue;
                for (ComponentInfo c : components) {
                    component(c, pi.applicationInfo);
                }
            }
        } else {
            pi = new PackageInfo();
            pi.packageName = applicationInfo.packageName;
            pi.versionName = versionName;
            pi.setLongVersionCode(versionCode);
            pi.applicationInfo = applicationInfo;
            pi.activities = activities.toArray(new ActivityInfo[0]);
        }
        pi.firstInstallTime = pi.lastUpdateTime = System.currentTimeMillis();
        return pi;
    }
}
