import java.io.DataInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.TreeMap;
import java.util.stream.Stream;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

/**
 * Writes the framework's app-compat changes as a Java table (docs/e2e.md): the system
 * server tells each app process which changes are disabled for it (bindApplication's
 * disabledCompatChanges), as PlatformCompat does from the compat config Soong generates.
 * Without the list every change is enabled for every app, whatever its target SDK
 * (e.g. DISABLE_OPT_OUT_EDGE_TO_EDGE, which ignores an app's
 * windowOptOutEdgeToEdgeEnforcement).
 *
 * <p>Reads the class files of framework.jar's classes (a directory or a jar): each
 * {@code static final long} field annotated {@code @ChangeId} (CLASS retention, so
 * RuntimeInvisibleAnnotations), with {@code @Disabled}, {@code @EnabledSince} or
 * {@code @EnabledAfter(targetSdkVersion = N)}, {@code @LoggingOnly}.
 *
 * <pre>java CompatChangesGen.java CLASSES OUT_DIR PACKAGE</pre>
 */
public final class CompatChangesGen {
    private static final String ANNOTATIONS = "Landroid/compat/annotation/";

    /** A change: kind 0 enabled, 1 disabled, 2 enabled since SDK, 3 enabled after SDK, 4 logging. */
    record Change(long id, int kind, int sdk, String where) {
    }

    public static void main(String[] args) throws IOException {
        if (args.length != 3) {
            System.err.println("usage: CompatChangesGen CLASSES OUT_DIR PACKAGE");
            System.exit(2);
        }
        TreeMap<Long, Change> changes = new TreeMap<>();
        Path classes = Path.of(args[0]);
        if (Files.isDirectory(classes)) {
            try (Stream<Path> files = Files.walk(classes)) {
                for (Path p : (Iterable<Path>) files.filter(f -> f.toString().endsWith(".class"))::iterator) {
                    try (InputStream in = Files.newInputStream(p)) {
                        scan(in.readAllBytes(), changes);
                    }
                }
            }
        } else {
            try (ZipFile zip = new ZipFile(classes.toFile())) {
                for (ZipEntry e : java.util.Collections.list(zip.entries())) {
                    if (!e.getName().endsWith(".class")) continue;
                    try (InputStream in = zip.getInputStream(e)) {
                        scan(in.readAllBytes(), changes);
                    }
                }
            }
        }
        String pkg = args[2];
        Path dir = Path.of(args[1], pkg.split("\\."));
        Files.createDirectories(dir);
        StringBuilder s = new StringBuilder();
        s.append("// Generated by app/gen/CompatChangesGen.java from framework.jar's @ChangeId fields.\n");
        s.append("// Do not edit.\npackage ").append(pkg).append(";\n\n");
        s.append("/** framework.jar's app-compat changes: {id, kind, sdk} (see CompatChanges). */\n");
        s.append("public final class CompatChangeTable {\n");
        s.append("    private CompatChangeTable() {\n    }\n\n");
        s.append("    public static final long[][] CHANGES = {\n");
        int[] counts = new int[5];
        for (Change c : changes.values()) {
            s.append("        {").append(c.id).append("L, ").append(c.kind).append(", ").append(c.sdk)
                    .append("},  // ").append(c.where).append('\n');
            counts[c.kind]++;
        }
        s.append("    };\n}\n");
        Files.writeString(dir.resolve("CompatChangeTable.java"), s, StandardCharsets.UTF_8);
        System.out.println("CompatChangesGen: " + changes.size() + " changes (" + counts[1]
                + " disabled, " + counts[2] + " enabled since an SDK, " + counts[3]
                + " enabled after an SDK, " + counts[4] + " logging only)");
    }

    /** The changes a class file declares. */
    static void scan(byte[] bytes, TreeMap<Long, Change> out) throws IOException {
        DataInputStream in = new DataInputStream(new java.io.ByteArrayInputStream(bytes));
        if (in.readInt() != 0xCAFEBABE) return;
        in.readUnsignedShort();
        in.readUnsignedShort();
        int n = in.readUnsignedShort();
        Object[] pool = new Object[n];
        for (int i = 1; i < n; i++) {
            int tag = in.readUnsignedByte();
            switch (tag) {
                case 1 -> pool[i] = in.readUTF();
                case 3 -> pool[i] = in.readInt();
                case 4 -> in.readInt();
                case 5 -> { pool[i] = in.readLong(); i++; }
                case 6 -> { in.readLong(); i++; }
                case 7 -> pool[i] = new int[] {in.readUnsignedShort()};
                case 8, 16, 19, 20 -> in.readUnsignedShort();
                case 9, 10, 11, 12, 17, 18 -> in.readInt();
                case 15 -> { in.readUnsignedByte(); in.readUnsignedShort(); }
                default -> throw new IOException("constant pool tag " + tag);
            }
        }
        in.readUnsignedShort();  // access
        String className = (String) pool[((int[]) pool[in.readUnsignedShort()])[0]];
        in.readUnsignedShort();  // super
        int interfaces = in.readUnsignedShort();
        for (int i = 0; i < interfaces; i++) in.readUnsignedShort();
        int fields = in.readUnsignedShort();
        for (int f = 0; f < fields; f++) {
            in.readUnsignedShort();
            String name = (String) pool[in.readUnsignedShort()];
            String desc = (String) pool[in.readUnsignedShort()];
            int attrs = in.readUnsignedShort();
            Long value = null;
            boolean changeId = false;
            int kind = 0, sdk = 0;
            for (int a = 0; a < attrs; a++) {
                String attr = (String) pool[in.readUnsignedShort()];
                byte[] body = in.readNBytes(in.readInt());
                if (attr.equals("ConstantValue") && desc.equals("J")) {
                    int idx = ((body[0] & 0xff) << 8) | (body[1] & 0xff);
                    if (pool[idx] instanceof Long l) value = l;
                } else if (attr.equals("RuntimeInvisibleAnnotations")
                        || attr.equals("RuntimeVisibleAnnotations")) {
                    DataInputStream an = new DataInputStream(new java.io.ByteArrayInputStream(body));
                    int count = an.readUnsignedShort();
                    for (int i = 0; i < count; i++) {
                        String type = (String) pool[an.readUnsignedShort()];
                        int pairs = an.readUnsignedShort();
                        Integer target = null;
                        for (int p = 0; p < pairs; p++) {
                            String key = (String) pool[an.readUnsignedShort()];
                            Object v = elementValue(an, pool);
                            if (key.equals("targetSdkVersion") && v instanceof Integer iv) target = iv;
                        }
                        if (!type.startsWith(ANNOTATIONS)) continue;
                        switch (type.substring(ANNOTATIONS.length())) {
                            case "ChangeId;" -> changeId = true;
                            case "Disabled;" -> kind = 1;
                            case "EnabledSince;" -> { kind = 2; sdk = target != null ? target : 0; }
                            case "EnabledAfter;" -> { kind = 3; sdk = target != null ? target : 0; }
                            case "LoggingOnly;" -> kind = 4;
                            default -> { }
                        }
                    }
                }
            }
            if (changeId && value != null) {
                out.putIfAbsent(value, new Change(value, kind, sdk,
                        className.replace('/', '.') + "." + name));
            }
        }
    }

    /** Reads an element_value; returns an Integer for an int constant, else null. */
    private static Object elementValue(DataInputStream in, Object[] pool) throws IOException {
        int tag = in.readUnsignedByte();
        switch (tag) {
            case 'B', 'C', 'I', 'S', 'Z', 'D', 'F', 'J', 's' -> {
                Object v = pool[in.readUnsignedShort()];
                return tag == 'I' ? v : null;
            }
            case 'e' -> { in.readUnsignedShort(); in.readUnsignedShort(); return null; }
            case 'c' -> { in.readUnsignedShort(); return null; }
            case '@' -> {
                in.readUnsignedShort();
                int pairs = in.readUnsignedShort();
                for (int p = 0; p < pairs; p++) { in.readUnsignedShort(); elementValue(in, pool); }
                return null;
            }
            case '[' -> {
                int count = in.readUnsignedShort();
                for (int i = 0; i < count; i++) elementValue(in, pool);
                return null;
            }
            default -> throw new IOException("element_value tag " + (char) tag);
        }
    }
}
