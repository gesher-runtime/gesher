import java.io.IOException;
import java.lang.reflect.Constructor;
import java.lang.reflect.GenericArrayType;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.Type;
import java.lang.reflect.TypeVariable;
import java.lang.reflect.WildcardType;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Writes, for each AIDL interface {@code IFoo} named, a concrete {@code IFoo.Stub} that
 * delegates every method to an {@code IFoo} it is given:
 *
 * <pre>
 *   java -cp FRAMEWORK_CLASSES app/gen/StubGen.java OUT_DIR PACKAGE IFACE...
 *   -> OUT_DIR/PACKAGE/IFooStub.java: public final class IFooStub extends IFoo.Stub
 * </pre>
 *
 * <p>The Stub's generated onTransact unmarshals calls from other processes; the stand-in
 * services (com.gesher.server.StandIn) are proxies over the interface, and a Stub, being
 * abstract, cannot be one. The interfaces are read by reflection from framework.jar's
 * classes, so the stubs always match the framework they are compiled against. Run with
 * {@code -XX:+UnlockDiagnosticVMOptions -XX:-BytecodeVerificationRemote}: reflection links the classes, and the
 * framework's code refers to libcore classes the JDK does not have.
 */
public final class StubGen {
    public static void main(String[] args) throws Exception {
        if (args.length < 3) {
            System.err.println("usage: StubGen OUT_DIR PACKAGE IFACE...");
            System.exit(2);
        }
        Path dir = Path.of(args[0], args[1].split("\\."));
        Files.createDirectories(dir);
        ClassLoader loader = StubGen.class.getClassLoader();
        for (int i = 2; i < args.length; i++) {
            write(dir, args[1], Class.forName(args[i], false, loader), loader);
        }
    }

    private static void write(Path dir, String pkg, Class<?> iface, ClassLoader loader)
            throws IOException, ClassNotFoundException {
        Class<?> stub = Class.forName(iface.getName() + "$Stub", false, loader);
        String name = iface.getSimpleName() + "Stub";
        String ifaceName = src(iface);
        StringBuilder s = new StringBuilder();
        s.append("// Generated by app/gen/StubGen.java from framework.jar's ")
                .append(iface.getName()).append(". Do not edit.\n");
        s.append("package ").append(pkg).append(";\n\n");
        s.append("/** A concrete {@code ").append(iface.getSimpleName())
                .append(".Stub} delegating every method to an implementation. */\n");
        s.append("@SuppressWarnings({\"deprecation\", \"rawtypes\", \"unchecked\"})\n");
        s.append("public final class ").append(name).append(" extends ").append(src(stub))
                .append(" {\n");
        s.append("    private final ").append(ifaceName).append(" mImpl;\n\n");
        s.append("    public ").append(name).append("(").append(ifaceName).append(" impl) {\n");
        if (hasEnforcerConstructor(stub)) {
            // The Stub() constructor of an interface with @EnforcePermission methods asks
            // ActivityThread for the system context; these implementations enforce none.
            s.append("        super(new android.os.PermissionEnforcer() {});\n");
        }
        s.append("        mImpl = impl;\n");
        s.append("    }\n");

        Map<String, Method> methods = new LinkedHashMap<>();
        List<Method> all = new ArrayList<>(Arrays.asList(stub.getMethods()));
        all.sort(Comparator.comparing(Method::getName)
                .thenComparing(m -> Arrays.toString(m.getParameterTypes())));
        for (Method m : all) {
            if (!Modifier.isAbstract(m.getModifiers())) continue;
            methods.putIfAbsent(m.getName() + Arrays.toString(m.getParameterTypes()), m);
        }
        for (Method m : methods.values()) {
            s.append("\n    @Override\n    public ");
            TypeVariable<Method>[] vars = m.getTypeParameters();
            if (vars.length > 0) {
                s.append("<");
                for (int i = 0; i < vars.length; i++) {
                    if (i > 0) s.append(", ");
                    s.append(vars[i].getName());
                    Type[] bounds = vars[i].getBounds();
                    if (bounds.length > 0 && bounds[0] != Object.class) {
                        s.append(" extends ");
                        for (int j = 0; j < bounds.length; j++) {
                            if (j > 0) s.append(" & ");
                            s.append(src(bounds[j]));
                        }
                    }
                }
                s.append("> ");
            }
            s.append(src(m.getGenericReturnType())).append(' ').append(m.getName()).append('(');
            Type[] params = m.getGenericParameterTypes();
            for (int i = 0; i < params.length; i++) {
                if (i > 0) s.append(", ");
                s.append(src(params[i])).append(" p").append(i);
            }
            s.append(')');
            Class<?>[] exceptions = m.getExceptionTypes();
            for (int i = 0; i < exceptions.length; i++) {
                s.append(i == 0 ? " throws " : ", ").append(src(exceptions[i]));
            }
            s.append(" {\n        ");
            if (m.getReturnType() != void.class) s.append("return ");
            s.append("mImpl.").append(m.getName()).append('(');
            for (int i = 0; i < params.length; i++) {
                if (i > 0) s.append(", ");
                s.append('p').append(i);
            }
            s.append(");\n    }\n");
        }
        s.append("}\n");
        Files.writeString(dir.resolve(name + ".java"), s, StandardCharsets.UTF_8);
        System.out.println("StubGen: " + pkg + "." + name + " (" + methods.size()
                + " methods)");
    }

    private static boolean hasEnforcerConstructor(Class<?> stub) {
        for (Constructor<?> c : stub.getDeclaredConstructors()) {
            Class<?>[] p = c.getParameterTypes();
            if (p.length == 1 && p[0].getName().equals("android.os.PermissionEnforcer")) {
                return true;
            }
        }
        return false;
    }

    /** {@code t} as Java source. */
    private static String src(Type t) {
        if (t instanceof Class<?> c) {
            if (c.isArray()) return src(c.getComponentType()) + "[]";
            return c.getCanonicalName();
        }
        if (t instanceof ParameterizedType p) {
            StringBuilder s = new StringBuilder(src(p.getRawType())).append('<');
            Type[] args = p.getActualTypeArguments();
            for (int i = 0; i < args.length; i++) {
                if (i > 0) s.append(", ");
                s.append(src(args[i]));
            }
            return s.append('>').toString();
        }
        if (t instanceof GenericArrayType g) {
            return src(g.getGenericComponentType()) + "[]";
        }
        if (t instanceof WildcardType w) {
            if (w.getLowerBounds().length > 0) return "? super " + src(w.getLowerBounds()[0]);
            Type[] upper = w.getUpperBounds();
            if (upper.length > 0 && upper[0] != Object.class) return "? extends " + src(upper[0]);
            return "?";
        }
        if (t instanceof TypeVariable<?> v) {
            return v.getName();
        }
        throw new IllegalArgumentException("type " + t);
    }
}
