#!/usr/bin/env python3
"""Generates EGL and OpenGL ES functions in the executable that forward to ANGLE.

  gen_gl_forwarders.py <out.cc> <opengl include dir> <source defining some...>

The framework's Java bindings (com.google.android.gles_jni, android.opengl;
cmake/aosp/opengl.cmake, docs/angle.md) call eglXxx/glXxx directly, as code
linked against libEGL.so and libGLESv*.so. dalvikvm does not link ANGLE's
import libraries (it starts without the DLLs; ADR 0023), so this defines every
function the Khronos headers declare (the headers compat/bionic/gen_gl_thunks.py
reads) as an extern "C" Microsoft-ABI function that calls ANGLE's entry point,
resolved on first call through gesher_egl_proc (compat/bionic/egl_gles.cc).
Both sides are Microsoft x64, so callbacks pass through as they are.

The functions defined by hand (EGL with Android's meanings: the displays,
configs and window surfaces of compat/hwui/gl/angle_gl.cc and
compat/opengl/opengl_jni.cc) are found in the sources named on the command
line and left out here.

Types the headers spell with `long` (GLsizeiptr, GLintptr: AOSP's khrplatform.h
is for LP64 Android) are 32 bits under mingw and 64 bits in ANGLE: a
forwarder takes them as the header spells them and passes them widened
(gen_gl_thunks.py's LP64_TYPES).
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'bionic'))
import gen_gl_thunks  # noqa: E402

# Callback types whose prototypes spell sizes with `long` (EGLsizeiANDROID):
# ANGLE would call them with 64-bit sizes. Nothing in the executable sets them.
LEFT_OUT_TYPES = ('EGLSetBlobFuncANDROID', 'EGLGetBlobFuncANDROID')

DEFINED = re.compile(r'\b(?:EGLAPIENTRY|GL_APIENTRY|KHRONOS_APIENTRY)\s+((?:egl|gl)[A-Z]\w*)\s*\(')


def main():
    out, include_dir, sources = sys.argv[1], sys.argv[2], sys.argv[3:]
    funcs, order = gen_gl_thunks.parse(include_dir)
    defined = set()
    for source in sources:
        with open(source, encoding='utf-8') as f:
            defined.update(DEFINED.findall(f.read()))
    names = [n for n in order
             if funcs[n][2] != gen_gl_thunks.EXTRA and n not in defined
             and not any(re.search(r'\b' + t + r'\b',
                                   funcs[n][0] + ' ' + ' '.join(p for p, _ in funcs[n][1]))
                         for t in LEFT_OUT_TYPES)]
    lines = [
        '// Generated by compat/opengl/gen_gl_forwarders.py from frameworks/native/opengl/include',
        '// (' + ', '.join(gen_gl_thunks.HEADERS) + '). Do not edit.',
        '',
        '#include "gl_forwarders.h"',
        '',
        'namespace {',
        '',
        f'std::atomic<void*> g_fn[{len(names)}];',
        '',
        'inline void* Fn(int index, const char* name) {',
        '  void* p = g_fn[index].load(std::memory_order_acquire);',
        '  if (p == nullptr) {',
        '    p = gesher_gl_forwarder_resolve(name);',
        '    g_fn[index].store(p, std::memory_order_release);',
        '  }',
        '  return p;',
        '}',
        '',
        '}  // namespace',
        '',
        'extern "C" {',
        '',
    ]
    for i, name in enumerate(names):
        ret, params, _ = funcs[name]
        decl = ', '.join(f'{t} a{j}{arr}' for j, (t, arr) in enumerate(params)) or 'void'
        types = ', '.join(gen_gl_thunks.fixed_width(t) + ('*' if arr else '')
                          for t, arr in params) or 'void'
        call = ', '.join(f'a{j}' for j in range(len(params)))
        fixed_ret = gen_gl_thunks.fixed_width(ret)
        target = f'reinterpret_cast<{fixed_ret} (KHRONOS_APIENTRY*)({types})>(Fn({i}, "{name}"))({call})'
        lines.append(f'{ret} KHRONOS_APIENTRY {name}({decl}) {{')
        if ret == 'void':
            lines.append(f'  {target};')
        elif fixed_ret != ret:
            lines.append(f'  return static_cast<{ret}>({target});')
        else:
            lines.append(f'  return {target};')
        lines.append('}')
    lines += ['', '}  // extern "C"', '']
    tmp = out + '.tmp'
    with open(tmp, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    os.replace(tmp, out)
    print(f'gen_gl_forwarders: {len(names)} forwarders, {len(defined)} defined by hand')


if __name__ == '__main__':
    main()
