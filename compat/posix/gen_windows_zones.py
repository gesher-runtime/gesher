#!/usr/bin/env python3
"""Generates gesher-base's Windows time zone table (src/windows_zones.cc) from
ICU's windowsZones.txt (CLDR's windowsZones.xml), in the pinned external/icu:

  gen_windows_zones.py <windowsZones.txt> <out.inc>

Each entry maps a Windows time zone id and a region (ISO 3166 alpha-2, or 001
for the zone's default) to the first, canonical IANA id CLDR lists for it.
"""
import re
import sys


def tokens(text):
    # ICU resource bundle syntax: names, quoted strings (adjacent ones are one
    # string), braces; // comments.
    text = re.sub(r'//[^\n]*', '', text)
    for m in re.finditer(r'"((?:[^"\\]|\\.)*)"|([{}])|([^\s{}"]+)', text):
        if m.group(1) is not None:
            yield ('str', m.group(1))
        elif m.group(2) is not None:
            yield (m.group(2), m.group(2))
        else:
            yield ('name', m.group(3))


def parse(text):
    """Returns [(windows_id, region, iana)] from mapTimezones."""
    entries = []
    stack = []  # names of the open tables
    pending_key = None
    pending_strings = []
    for kind, value in tokens(text):
        if kind in ('str', 'name') and pending_strings is not None and stack and len(stack) == 4:
            pending_strings.append(value)
            continue
        if kind == '{':
            stack.append(pending_key)
            pending_key = None
            pending_strings = []
        elif kind == '}':
            if len(stack) == 4 and stack[1] == 'mapTimezones':
                ids = ''.join(pending_strings).split()
                if ids:
                    entries.append((stack[2], stack[3], ids[0]))
            stack.pop()
            pending_strings = []
        else:
            if pending_key is not None and len(stack) < 4:
                pending_key = pending_key + value  # a split quoted key
            else:
                pending_key = value
    return entries


def main():
    src, out = sys.argv[1], sys.argv[2]
    with open(src, encoding='utf-8-sig') as f:
        entries = parse(f.read())
    if len(entries) < 100:
        sys.exit('%s: only %d entries found' % (src, len(entries)))
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by compat/posix/gen_windows_zones.py from %s. Do not edit.\n'
                % src.replace('\\', '/').split('/external/')[-1])
        for windows_id, region, iana in sorted(entries):
            f.write('{"%s", "%s", "%s"},\n' % (windows_id, region, iana))


if __name__ == '__main__':
    main()
