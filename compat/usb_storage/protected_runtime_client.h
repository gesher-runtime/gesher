#pragma once

#include <cstdint>
#include <string>
#include <string_view>
#include <vector>

namespace gesher::usb_storage {

// Set only by the native executable entry point, before Android/guest code.
// The locator is a route, not a capability: the service authenticates the exact
// retained process object on every request and the client checks its kernel peer.
bool ConfigureProtectedRuntimeStartup(std::string_view locator,
                                     std::string_view authority_pid,
                                     std::string_view desktop_session);
bool ProtectedRuntimeEnabled();
bool ProtectedRuntimeCredentials(uint32_t* uid, uint32_t* gid);
bool ProtectedRuntimeIsSystemServer();
// An owned duplicate of the executable's unnamed property-writer mutex.
// Available only after authenticated system_server initialization.
uint32_t ProtectedPropertyMutex(uint64_t* handle);
// An owned reduced duplicate of the authority-created mutex for this package's
// log, shared by its admitted processes and by every DLL in one executable.
uint32_t ProtectedLogMutex(uint64_t* handle);

struct ProtectedStartupResources {
  uint64_t standard_handles[3]{};
  uint64_t signal_section = 0;
  uint64_t signal_event = 0;
  uint64_t block_pipe = 0;
  uint64_t block_gate = 0;
  uint64_t block_revoked = 0;
};
// One-shot native bootstrap, before running any guest code. Caller installs
// stdio in the actual runtime FD table and attaches the optional block broker.
uint32_t ProtectedInitializeResources(ProtectedStartupResources* resources);

// Explicit optional-companion launch. Uses the fixed installed authority image
// and Windows UAC; cancellation is returned as a Win32 error. Never starts the
// ordinary per-user Android runtime as a fallback.
uint32_t StartProtectedRuntime(const std::u16string& apk_path);

struct ProtectedSpawnSpec {
  std::u16string package_name;
  std::u16string process_name;
  std::u16string apk_path;
  // Lowercase hex SHA-256; generated by the trusted system_server after full
  // Android APK signature verification, never an application-supplied claim.
  std::u16string apk_sha256;
  std::u16string signer_sha256;
  uint32_t uid = 0;
  uint32_t target_sdk = 0;
  uint64_t start_sequence = 0;
  // Only documented display, proxy, INTERNET and window settings are accepted.
  // Runtime roots, identity, executable, classpath and native routes are derived
  // by the authority from its sealed session, not from these strings.
  std::vector<std::u16string> environment;
};

struct ProtectedChild {
  uint32_t pid = 0;
  uint64_t start_time = 0;
};

uint32_t ProtectedSpawn(const ProtectedSpawnSpec& spec, ProtectedChild* child);
uint32_t ProtectedChildStatus(uint32_t pid, uint64_t start_time, uint32_t* exit_code,
                              bool* running);
uint32_t ProtectedKill(uint32_t pid, uint64_t start_time);
uint32_t ProtectedSignal(uint32_t pid, uint64_t start_time, int signal);
uint32_t ProtectedSignalChild(uint32_t pid, int signal);

// Only the enrolled system_server can approve a specific, currently admitted
// application's selected USB disk. Permission is a one-time session grant;
// the process identity, media generation and expiry remain authority-side.
uint32_t ProtectedGrantBlock(uint32_t pid, uint64_t start_time,
                             const std::u16string& device_interface,
                             bool allow_write, uint32_t lifetime_milliseconds);
uint32_t ProtectedRevokeBlock(uint32_t pid, uint64_t start_time);

struct ProtectedCommandSpec {
  std::vector<std::u16string> arguments;
  std::vector<std::u16string> environment;
  std::u16string working_directory;
  // Handles already owned by the authenticated parent. Only validated regular
  // files and non-authority pipes for fd 0/1/2 can be duplicated; no other FDs.
  uint64_t standard_handles[3]{};
  bool privileged_root = false;
};
struct ProtectedCommandChild {
  uint32_t pid = 0;
  uint64_t start_time = 0;
  uint64_t wait_handle = 0;
};
uint32_t ProtectedSpawnCommand(const ProtectedCommandSpec& spec, ProtectedCommandChild* child);

}  // namespace gesher::usb_storage
