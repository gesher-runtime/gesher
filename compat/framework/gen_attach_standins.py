#!/usr/bin/env python3
"""Writes compat/framework/attach_standins.cc: stand-ins for the graphics and
view natives that an app process attached to the system server reaches
(ActivityThread's handleBindApplication, handleLaunchActivity and
handleResumeActivity), until the graphics track's real ones are linked
(docs/services.md).

  gen_attach_standins.py <out.cc> <frameworks/base> <class>=<source>[:<table>] ...

<source> is relative to <frameworks/base>; <class> uses '.' for '$'. The
output is committed: the sources of libs/hwui/jni are not in the CI checkout
(aosp.lock's sparse set), so it is generated from a full android-16.0.0_r4
frameworks/base and checked in. Rerun it with the same arguments (the header
of the output lists them) when the pinned AOSP changes.

Every native answers zero, false, null or 0.0 by its return type, except:
a long-returning native whose name says it hands out a finalizer, destructor
or release function answers a function that frees; one whose name says it
creates an object answers a small zeroed block (NativeAllocationRegistry
refuses 0); SPECIALS below. The answers are System V functions that take no
parameters (ART calls natives with the System V ABI, where the caller pops
the arguments), so one answers every signature.
"""
import re
import sys

ENTRY = re.compile(r'\{\s*"(\w+)"\s*,\s*((?:"[^"]*"\s*)+),')
TABLE = r'\b{}\s*\[\s*\]\s*=\s*\{{'

FREE = re.compile(r'(Finalizer|Destructor|ReleaseFunc|FreeFunc|GetFree)', re.I)
CREATE = re.compile(r'^n(ative)?_?(Create|Init|Make|New|Copy|Constructor)', re.I)

# (class, name) -> answer
SPECIALS = {
    # A display event receiver that never delivers events (vsync is off,
    # debug.choreographer.vsync=false), but exists.
    ('android/view/DisplayEventReceiver', 'nativeInit'): 'create',
}


def entries(path, table):
    # newline=None (universal newlines): a Windows checkout's CRLF reads as \n.
    text = open(path, encoding='utf-8', newline=None).read()
    m = re.search(TABLE.format(table), text)
    if not m:
        sys.exit(f'{path}: no table {table}')
    # The table ends at a '};' on its own line, or right after the last entry.
    e = re.compile(r'\n\s*\};|(?<=\})\};').search(text, m.end())
    if not e:
        sys.exit(f'{path}: table {table} has no end')
    end = e.start()
    out = []
    for e in ENTRY.finditer(text, m.end(), end):
        out.append((e.group(1), ''.join(re.findall(r'"([^"]*)"', e.group(2)))))
    if not out:
        sys.exit(f'{path}: table {table} has no entries')
    return out


def answer(cls, name, sig):
    if (cls, name) in SPECIALS:
        return SPECIALS[(cls, name)]
    ret = sig[sig.index(')') + 1]
    if ret == 'J' and FREE.search(name):
        return 'freeFunction'
    if ret == 'J' and CREATE.search(name):
        return 'create'
    return 'zeroFloat' if ret in 'FD' else 'zero'


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    out_path, base = sys.argv[1], sys.argv[2]
    out = [
        '// Generated by compat/framework/gen_attach_standins.py; do not edit.',
        '// Arguments after the output file and frameworks/base:',
    ]
    out += [f'//     {a}' for a in sys.argv[3:]]
    out += [
        '//',
        '// Stand-ins for graphics and view natives on the attached app process\'s',
        '// path (services track, docs/services.md); register_gesher_attach_standins',
        '// runs before the graphics registrations, so real natives replace these.',
        '',
        '#include <jni.h>',
        '#include <stdlib.h>',
        '',
        '#include <log/log.h>',
        '',
        '#define SYSV __attribute__((sysv_abi))',
        '',
        'namespace {',
        '',
        'void FreeBlock(void* ptr) { free(ptr); }',
        '',
        'SYSV jlong Standin_zero() { return 0; }',
        'SYSV jdouble Standin_zeroFloat() { return 0.0; }',
        'SYSV jlong Standin_create() { return reinterpret_cast<jlong>(calloc(1, 64)); }',
        'SYSV jlong Standin_freeFunction() { return reinterpret_cast<jlong>(&FreeBlock); }',
        '',
    ]
    tables = []
    for arg in sys.argv[3:]:
        cls, source = arg.split('=', 1)
        cls = cls.replace('.', '$')
        table = 'gMethods'
        m = re.match(r'(.*):([A-Za-z_]\w*)$', source)
        if m:
            source, table = m.group(1), m.group(2)
        var = 'k' + re.sub(r'\W', '_', cls)
        out.append(f'const JNINativeMethod {var}[] = {{')
        for name, sig in entries(f'{base}/{source}', table):
            fn = 'Standin_' + answer(cls, name, sig)
            out.append(f'    {{"{name}", "{sig}", reinterpret_cast<void*>(&{fn})}},')
        out.append('};')
        out.append('')
        tables.append((cls, var))
    out += [
        'const struct {',
        '  const char* className;',
        '  const JNINativeMethod* methods;',
        '  int count;',
        '} kTables[] = {',
    ]
    for cls, var in tables:
        out.append(f'    {{"{cls}", {var}, sizeof({var}) / sizeof({var}[0])}},')
    out += [
        '};',
        '',
        '}  // namespace',
        '',
        'int register_gesher_attach_standins(JNIEnv* env) {',
        '  for (const auto& t : kTables) {',
        '    jclass clazz = env->FindClass(t.className);',
        '    if (clazz == nullptr) {',
        '      env->ExceptionClear();',
        '      continue;',
        '    }',
        '    // Not fatal (RegisterNatives, not jniRegisterNativeMethods, which aborts): a',
        '    // table that does not match its class is left out.',
        '    if (env->RegisterNatives(clazz, t.methods, t.count) < 0) {',
        '      env->ExceptionClear();',
        '      ALOGE("libandroid_runtime: registering stand-ins for %s failed", t.className);',
        '    }',
        '    env->DeleteLocalRef(clazz);',
        '  }',
        '  return 0;',
        '}',
    ]
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
