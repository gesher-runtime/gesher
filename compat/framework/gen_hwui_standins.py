#!/usr/bin/env python3
"""Generates libandroid_runtime's stand-in tables for hwui's natives.

  gen_hwui_standins.py <out.cc> <class>=<hwui jni source>[:<table>] ...

hwui (and Skia) are left out until views (docs/framework-natives.md), but the
headless lifecycle constructs View objects, whose constructors and setters
call hwui's natives (RenderNode). Nothing is drawn, so each native of the
listed tables is registered with an answer that holds no state: zero, false,
null or 0.0 (by its JNI return type). The few that must create something or
return a function are hand-written in hwui_standins.cc and named in SPECIALS;
the table, with each native's name and signature, is read from hwui's own
JNI source, so it matches framework.jar.

The answers are System V functions that take no parameters: ART calls natives
with the System V ABI (docs/decisions/0006-managed-abi.md), where the caller
pops the arguments, so one function answers every signature; floating-point
results come back in xmm0, the others in rax.
"""
import re
import sys

ENTRY = re.compile(r'\{\s*"(\w+)"\s*,\s*((?:"[^"]*"\s*)+),')
TABLE = r'\b{}\s*\[\s*\]\s*=\s*\{{'

# (class, native name) -> hand-written function in hwui_standins.cc.
# A fresh RenderNode's defaults, where they are not zero, so View's getters
# read what they would on a device before anything is set.
SPECIALS = {
    ('android/graphics/RenderNode', 'nCreate'): 'RenderNode_create',
    ('android/graphics/RenderNode', 'nGetNativeFinalizer'): 'Standin_getFreeFunction',
    ('android/graphics/RenderNode', 'nIsValid'): 'Standin_true',
    ('android/graphics/RenderNode', 'nGetClipToBounds'): 'Standin_true',
    ('android/graphics/RenderNode', 'nHasOverlappingRendering'): 'Standin_true',
    ('android/graphics/RenderNode', 'nHasIdentityMatrix'): 'Standin_true',
    ('android/graphics/RenderNode', 'nGetAllowForceDark'): 'Standin_true',
    ('android/graphics/RenderNode', 'nGetAlpha'): 'Standin_oneFloat',
    ('android/graphics/RenderNode', 'nGetScaleX'): 'Standin_oneFloat',
    ('android/graphics/RenderNode', 'nGetScaleY'): 'Standin_oneFloat',
}
# The return type each special's function declares.
FLOAT_SPECIALS = {'Standin_oneFloat'}


def entries(path, table):
    text = open(path, encoding='utf-8').read()
    m = re.search(TABLE.format(table), text)
    if not m:
        sys.exit(f'{path}: no table {table}')
    end = text.index('\n};', m.end())
    out = []
    for e in ENTRY.finditer(text, m.end(), end):
        out.append((e.group(1), ''.join(re.findall(r'"([^"]*)"', e.group(2)))))
    if not out:
        sys.exit(f'{path}: table {table} has no entries')
    return out


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    out = [
        '// Generated by compat/framework/gen_hwui_standins.py; do not edit.',
        '#include <jni.h>',
        '',
        'namespace gesher_hwui {',
        '__attribute__((sysv_abi)) jlong Standin_zero();',
        '__attribute__((sysv_abi)) jdouble Standin_zeroFloat();',
    ]
    for symbol in sorted(set(SPECIALS.values())):
        ret = 'jdouble' if symbol in FLOAT_SPECIALS else 'jlong'
        out.append(f'__attribute__((sysv_abi)) {ret} {symbol}();')
    out.append('')
    classes = []
    for arg in sys.argv[2:]:
        cls, source = arg.split('=', 1)
        table = 'gMethods'
        if ':' in source[2:]:  # not a drive letter
            source, table = source.rsplit(':', 1)
        var = 'k' + re.sub(r'\W', '_', cls)
        out.append(f'static const JNINativeMethod {var}[] = {{')
        for name, sig in entries(source, table):
            ret = sig[sig.index(')') + 1]
            fn = SPECIALS.get((cls, name),
                              'Standin_zeroFloat' if ret in 'FD' else 'Standin_zero')
            out.append(f'    {{"{name}", "{sig}", reinterpret_cast<void*>(&{fn})}},')
        out.append('};')
        classes.append((cls, var))
    out.append('')
    out.append('struct StandinTable {')
    out.append('  const char* className;')
    out.append('  const JNINativeMethod* methods;')
    out.append('  int count;')
    out.append('};')
    out.append('')
    out.append('extern const StandinTable kStandinTables[] = {')
    for cls, var in classes:
        out.append(f'    {{"{cls}", {var}, sizeof({var}) / sizeof({var}[0])}},')
    out.append('};')
    out.append(f'extern const int kStandinTableCount = {len(classes)};')
    out.append('')
    out.append('}  // namespace gesher_hwui')
    with open(sys.argv[1], 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
