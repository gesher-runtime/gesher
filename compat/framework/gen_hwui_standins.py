#!/usr/bin/env python3
"""Generates libandroid_runtime's stand-in tables for hwui's natives.

  gen_hwui_standins.py <out.cc> <class>=<hwui jni source>[:<table>] ...

<class> is a JNI class name, with '.' before a nested class's name
(android/graphics/Matrix.ExtraNatives); <table> defaults to gMethods.

hwui (and Skia) are left out until views (docs/framework-natives.md), but the
headless lifecycle constructs View objects, whose constructors and setters
call hwui's natives (RenderNode). Nothing is drawn, so each native of the
listed tables is registered with an answer that holds no state: zero, false,
null or 0.0 (by its JNI return type). The few that must create something or
return a function are hand-written in hwui_standins.cc and named in SPECIALS;
the table, with each native's name and signature, is read from hwui's own
JNI source, so it matches framework.jar.

The answers are System V functions that take no parameters: ART calls natives
with the System V ABI (docs/decisions/0006-managed-abi.md), where the caller
pops the arguments, so one function answers every signature; floating-point
results come back in xmm0, the others in rax.
"""
import re
import sys

ENTRY = re.compile(r'\{\s*"(\w+)"\s*,\s*((?:"[^"]*"\s*)+),')
TABLE = r'\b{}\s*\[\s*\]\s*=\s*\{{'

# (class, native name[, signature]) -> hand-written function in
# hwui_standins.cc, a System V function with C linkage named gesher_hwui_<name>.
# A key with a signature takes precedence over one without.
SPECIALS = {
    # A fresh RenderNode's defaults, where they are not zero, so View's
    # getters read what they would on a device before anything is set.
    ('android/graphics/RenderNode', 'nCreate'): 'Standin_create',
    ('android/graphics/RenderNode', 'nGetNativeFinalizer'): 'Standin_getFreeFunction',
    ('android/graphics/RenderNode', 'nIsValid'): 'Standin_true',
    ('android/graphics/RenderNode', 'nGetClipToBounds'): 'Standin_true',
    ('android/graphics/RenderNode', 'nHasOverlappingRendering'): 'Standin_true',
    ('android/graphics/RenderNode', 'nHasIdentityMatrix'): 'Standin_true',
    ('android/graphics/RenderNode', 'nGetAllowForceDark'): 'Standin_true',
    ('android/graphics/RenderNode', 'nGetAlpha'): 'Standin_oneFloat',
    ('android/graphics/RenderNode', 'nGetScaleX'): 'Standin_oneFloat',
    ('android/graphics/RenderNode', 'nGetScaleY'): 'Standin_oneFloat',
    ('android/graphics/Paint', 'nInit'): 'Standin_create',
    ('android/graphics/Paint', 'nInitWithPaint'): 'Standin_create',
    ('android/graphics/Paint', 'nGetNativeFinalizer'): 'Standin_getFreeFunction',
    ('android/graphics/Matrix$ExtraNatives', 'nCreate'): 'Standin_create',
    ('android/graphics/Matrix$ExtraNatives', 'nGetNativeFinalizer'): 'Standin_getFreeFunction',
    ('android/graphics/Matrix', 'nIsIdentity'): 'Standin_true',
    ('android/graphics/Matrix', 'nIsAffine'): 'Standin_true',
    ('android/graphics/Matrix', 'nRectStaysRect'): 'Standin_true',
    # Path keeps its geometry: interpolators (PathInterpolator) flatten
    # Bézier curves with approximate().
    ('android/graphics/Path', 'nInit', '()J'): 'Path_init',
    ('android/graphics/Path', 'nInit', '(J)J'): 'Path_initCopy',
    ('android/graphics/Path', 'nGetFinalizer'): 'Path_getFinalizer',
    ('android/graphics/Path', 'nSet'): 'Path_set',
    ('android/graphics/Path', 'nReset'): 'Path_reset',
    ('android/graphics/Path', 'nRewind'): 'Path_reset',
    ('android/graphics/Path', 'nIsEmpty'): 'Path_isEmpty',
    ('android/graphics/Path', 'nMoveTo'): 'Path_moveTo',
    ('android/graphics/Path', 'nRMoveTo'): 'Path_rMoveTo',
    ('android/graphics/Path', 'nLineTo'): 'Path_lineTo',
    ('android/graphics/Path', 'nRLineTo'): 'Path_rLineTo',
    ('android/graphics/Path', 'nQuadTo'): 'Path_quadTo',
    ('android/graphics/Path', 'nRQuadTo'): 'Path_rQuadTo',
    ('android/graphics/Path', 'nCubicTo'): 'Path_cubicTo',
    ('android/graphics/Path', 'nRCubicTo'): 'Path_rCubicTo',
    ('android/graphics/Path', 'nClose'): 'Path_close',
    ('android/graphics/Path', 'nApproximate'): 'Path_approximate',
}


def entries(path, table):
    text = open(path, encoding='utf-8').read()
    m = re.search(TABLE.format(table), text)
    if not m:
        sys.exit(f'{path}: no table {table}')
    end = text.index('\n};', m.end())
    out = []
    for e in ENTRY.finditer(text, m.end(), end):
        out.append((e.group(1), ''.join(re.findall(r'"([^"]*)"', e.group(2)))))
    if not out:
        sys.exit(f'{path}: table {table} has no entries')
    return out


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    out = [
        '// Generated by compat/framework/gen_hwui_standins.py; do not edit.',
        '#include <jni.h>',
        '',
        '// Defined in hwui_standins.cc; only their addresses are taken here.',
        'extern "C" {',
        'void gesher_hwui_Standin_zero();',
        'void gesher_hwui_Standin_zeroFloat();',
    ]
    for symbol in sorted(set(SPECIALS.values())):
        out.append(f'void gesher_hwui_{symbol}();')
    out.append('}')
    out.append('')
    out.append('namespace gesher_hwui {')
    out.append('')
    classes = []
    for arg in sys.argv[2:]:
        cls, source = arg.split('=', 1)
        # Nested classes are given with '.', as '$' does not survive build
        # files and shells.
        cls = cls.replace('.', '$')
        table = 'gMethods'
        m = re.match(r'(.*):([A-Za-z_]\w*)$', source)
        if m:
            source, table = m.group(1), m.group(2)
        var = 'k' + re.sub(r'\W', '_', cls)
        out.append(f'static const JNINativeMethod {var}[] = {{')
        for name, sig in entries(source, table):
            ret = sig[sig.index(')') + 1]
            fn = SPECIALS.get((cls, name, sig)) or SPECIALS.get((cls, name)) or (
                'Standin_zeroFloat' if ret in 'FD' else 'Standin_zero')
            out.append(f'    {{"{name}", "{sig}", reinterpret_cast<void*>(&gesher_hwui_{fn})}},')
        out.append('};')
        classes.append((cls, var))
    out.append('')
    out.append('struct StandinTable {')
    out.append('  const char* className;')
    out.append('  const JNINativeMethod* methods;')
    out.append('  int count;')
    out.append('};')
    out.append('')
    out.append('extern const StandinTable kStandinTables[] = {')
    for cls, var in classes:
        out.append(f'    {{"{cls}", {var}, sizeof({var}) / sizeof({var}[0])}},')
    out.append('};')
    out.append(f'extern const int kStandinTableCount = {len(classes)};')
    out.append('')
    out.append('}  // namespace gesher_hwui')
    with open(sys.argv[1], 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
