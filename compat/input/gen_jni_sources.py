#!/usr/bin/env python3
"""Writes System V copies of libandroid_runtime's input natives (docs/input.md).

  gen_jni_sources.py <out-dir> <frameworks/base> <core/jni source>...

ART enters natives with the System V ABI (docs/decisions/0006-managed-abi.md).
Each `(void*) fn` of a source's JNI tables becomes `GESHER_JNI(fn)`, as
frameworks/base patch 0002 does for the sources framework.cmake compiles
(tools/jni-sysv-patch.py's rewrite, reused here). The copies are written into
the build tree rather than kept as a patch: the input sources then change
neither the AOSP cache key (patches/**) nor other tracks' patches
(docs/decisions/0027-input-channel-and-win32-translation.md). A copy is
rewritten only when its text changes, so ninja does not rebuild it needlessly.

EDITS are Gesher's changes to the sources, each a block that must be found
exactly once (the script fails otherwise, as a patch would).
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location(
    'jni_sysv_patch', os.path.join(HERE, '..', '..', 'tools', 'jni-sysv-patch.py'))
jsp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(jsp)


# A window session that gives no input channel (the services track's stand-in
# session; a channel whose socket could not cross processes) would make
# ViewRootImpl's WindowInputEventReceiver throw: the receiver gets a channel
# nothing writes to instead, and the window no input.
_NO_CHANNEL = """    if (inputChannel == nullptr) {
        jniThrowRuntimeException(env, "InputChannel is not initialized.");
        return 0;
    }
"""
EDITS = {
    'core/jni/android_view_InputEventReceiver.cpp': [(_NO_CHANNEL, """    if (inputChannel == nullptr) {
#ifdef GESHER
        // Gesher (compat/input/gen_jni_sources.py): no channel from the window
        // session; a channel nothing writes to, so the window gets no input.
        ALOGW("InputChannel is not initialized: this receiver gets no input (docs/input.md)");
        std::unique_ptr<InputChannel> unusedServer, client;
        if (InputChannel::openInputChannelPair("gesher-no-input", unusedServer, client) != OK) {
            jniThrowRuntimeException(env, "InputChannel is not initialized.");
            return 0;
        }
        inputChannel = std::move(client);
#else
        jniThrowRuntimeException(env, "InputChannel is not initialized.");
        return 0;
#endif
    }
""")],
}


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    out_dir, base = sys.argv[1], sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    for rel in sys.argv[3:]:
        with open(os.path.join(base, rel), encoding='utf-8', newline=None) as f:
            text = f.read()
        new = jsp.rewrite(rel, text)
        if new == text:
            sys.exit(f'{rel}: no table entry to rewrite')
        for old_block, new_block in EDITS.get(rel, []):
            if new.count(old_block) != 1:
                sys.exit(f'{rel}: a Gesher edit does not apply (found {new.count(old_block)} times)')
            new = new.replace(old_block, new_block)
        # The copy's own directory comes first for "..." includes; the original's
        # directory (core/jni) is on the include path after it.
        new = f'// Generated by compat/input/gen_jni_sources.py from {rel}; do not edit.\n' + new
        out = os.path.join(out_dir, os.path.basename(rel))
        old = None
        if os.path.exists(out):
            with open(out, encoding='utf-8', newline=None) as f:
                old = f.read()
        if old != new:
            with open(out, 'w', encoding='utf-8', newline='\n') as f:
                f.write(new)


if __name__ == '__main__':
    main()
