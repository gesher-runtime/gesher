#!/usr/bin/env python3
"""Validate the captured device corpus and reproduce its compact test data."""
import argparse
import hashlib
import json
from pathlib import Path
import re


def verify_numeric_return_reference(here, root):
    manifest = json.loads((here / 'android-numeric-return.json').read_text())
    for path, expected in (
            (root / manifest['fixture_source'], manifest['corrected_source_sha256']),
            (root / manifest['observation_source'], manifest['observation_source_sha256'])):
        if hashlib.sha256(path.read_bytes()).hexdigest() != expected:
            raise SystemExit(f'numeric return reference source mismatch: {path.name}')
    outputs = {}
    for observation in manifest['observations']:
        path = here / observation['output_file']
        if hashlib.sha256(path.read_bytes()).hexdigest() != observation['output_sha256']:
            raise SystemExit(f'numeric return observation mismatch: {path.name}')
        outputs[observation['name']] = path.read_text()
    initial = outputs['initial']
    failed = re.findall(r'^NUMERIC_RETURN_FAIL (full binary128 result|end pointer) '
                        r'sample=5 mode=([0-3]) api=([23]) seed=([01])$',
                        initial, re.MULTILINE)
    if len(set(failed)) != 32 or initial.count('NUMERIC_RETURN_FAIL ') != 32:
        raise SystemExit('initial wide-hex failure denominator changed')
    for name, failures in (('initial', 32), ('corrected', 0)):
        marker = f'NUMERIC_RETURN_DONE conversions=256 checks=1292 failures={failures}\n'
        if not outputs[name].endswith(marker):
            raise SystemExit('numeric return reference completion changed')
    if 'NUMERIC_RETURN_FAIL ' in outputs['corrected']:
        raise SystemExit('corrected numeric return reference has a failure')
    if not outputs['wide-hex'].endswith('WIDE_HEX_DONE\n'):
        raise SystemExit('incomplete wide-hex observation run')
    seen = set()
    for line in outputs['wide-hex'].splitlines()[:-1]:
        fields = line.split()
        if len(fields) != 7 or fields[0] != 'WIDE_HEX':
            raise SystemExit('malformed wide-hex observation')
        mode, api = map(int, fields[1:3])
        expected = manifest['narrow' if api < 2 else 'wide']
        if ((mode, api) in seen or mode not in range(4) or api not in range(4)
                or fields[3:] != [expected['bits'], str(expected['consumed']), '123', '1']):
            raise SystemExit('wide-hex observation values or denominator changed')
        seen.add((mode, api))
    if len(seen) != 16:
        raise SystemExit('incomplete wide-hex observations')
    print('Verified numeric return reference: 32 original failures, 16 observations, '
          '256 corrected conversions / 1292 checks')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    here = Path(__file__).resolve().parent
    root = here.parents[2]
    verify_numeric_return_reference(here, root)
    manifest = json.loads((here / 'android-api36-x86_64.json').read_text())
    for path, key in ((here / 'parse-reference.c', 'source_sha256'),
                      (root / 'tests/binary128/parse_cases.h', 'cases_sha256'),
                      (here / 'android-api36-x86_64.txt', 'observations_sha256'),
                      (here / 'android-fenv-control.txt', 'fenv_control_output_sha256')):
        if hashlib.sha256(path.read_bytes()).hexdigest() != manifest[key]:
            raise SystemExit(f'reference identity mismatch: {path.name}')
    text = (here / 'android-api36-x86_64.txt').read_text()
    rows = {}
    for line in text.splitlines():
        if not line.startswith('QUAD '):
            continue
        values = line.split()
        key = tuple(map(int, values[1:4]))
        if key in rows or len(values) != 9 or values[-1] != '1':
            raise SystemExit('duplicate, incomplete, or rounding-changing reference row')
        rows[key] = (values[4], *map(int, values[5:8]))
    count = manifest['cases']
    if len(rows) != count * 16 or not text.endswith('QUAD_REFERENCE_DONE\n'):
        raise SystemExit('incomplete reference corpus')
    out = ['// Generated by probes/native3/binary128/generate_expected.py.',
           '// Android API36 x86_64 observations; arithmetic flags are unqualified',
           '// by this emulator. See android-fenv-control.txt and the source manifest.',
           f'static constexpr Expected android_expected[{count}][4][2] = {{']
    for case in range(count):
        out.append('  {')
        for mode in range(4):
            entries = []
            for api in (0, 2):
                if rows[case, mode, api] != rows[case, mode, api + 1]:
                    raise SystemExit('locale alias observation differs')
                bits, end, error, flags = rows[case, mode, api]
                entries.append(f'{{UINT64_C(0x{bits[16:]}), UINT64_C(0x{bits[:16]}), {end}, {error}, {flags}}}')
            out.append('    {' + ', '.join(entries) + '},')
        out.append('  },')
    out += ['};', '']
    generated = '\n'.join(out)
    destination = root / 'tests/binary128/android_expected.inc'
    if args.check:
        if destination.read_text() != generated:
            raise SystemExit('generated Android expectations are stale')
    else:
        destination.write_text(generated)
    print(f'Verified {count * 16} Android rows and exact source/observation identities')


if __name__ == '__main__':
    main()
